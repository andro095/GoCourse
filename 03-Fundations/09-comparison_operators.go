package main

import "fmt"

func comparisonOperators() {
	age := 18
	fmt.Println(age > 18)
	fmt.Println(age >= 18)
	fmt.Println(age < 18)
	fmt.Println(age <= 18)
	fmt.Println(age == 18)
	fmt.Println(age != 18)

	isVIP := true

	fmt.Println(isVIP == true)
	fmt.Println(isVIP == false)
	fmt.Println(isVIP != true)
	fmt.Println(isVIP != false)

}
